"""Coach router — interview prep and mock interview sessions."""

from __future__ import annotations

import json
from typing import Annotated

from fastapi import APIRouter, Depends, Path
from pydantic import BaseModel
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from jobforce.db.engine import get_session
from jobforce.db.models import InterviewSession, JobListing
from jobforce.routers.errors import ApiError, ErrorCode, error_responses
from jobforce.routers.resume_schema import QuestionCategoryStr
from jobforce.services.coach import (
    QuestionNotFoundError,
    SessionNotFoundError,
    evaluate_answer,
    get_session_summary_data,
    store_prep_pack,
)

router = APIRouter(prefix="/coach", tags=["coach"])

SessionId = Annotated[int, Path(description="Interview session id")]


class QuestionIn(BaseModel):
    """A prep question generated by the /coach-prep skill."""

    id: str
    category: QuestionCategoryStr
    text: str
    source_url: str | None = None
    leetcode_url: str | None = None
    guidance: str | None = None


class PrepRequest(BaseModel):
    job_id: int
    questions: list[QuestionIn]


class QuestionOut(BaseModel):
    id: str
    category: QuestionCategoryStr
    text: str
    source_url: str | None = None
    leetcode_url: str | None = None
    guidance: str | None = None


class PrepSessionOut(BaseModel):
    session_id: int
    job_id: int
    questions: list[QuestionOut]


class AnswerRequest(BaseModel):
    question_id: str
    answer: str


class AnswerFeedbackOut(BaseModel):
    question_id: str
    feedback: str
    score: float


class SessionSummaryOut(BaseModel):
    session_id: int
    overall_score: float
    summary: str
    areas_to_improve: list[str]


@router.post(
    "/prep",
    response_model=PrepSessionOut,
    summary="Store a prep pack generated by /coach-prep",
    responses=error_responses(ErrorCode.JOB_NOT_FOUND),
)
async def post_prep(
    body: PrepRequest,
    session: Annotated[AsyncSession, Depends(get_session)],
) -> PrepSessionOut:
    """Save the skill's questions as a new interview session for the job. No AI runs
    on the backend; the skill generates the questions."""
    job = await session.get(JobListing, body.job_id)
    if job is None:
        raise ApiError(ErrorCode.JOB_NOT_FOUND, "Job listing not found")

    questions = [q.model_dump() for q in body.questions]
    result = await store_prep_pack(session, body.job_id, questions)

    return PrepSessionOut(
        session_id=result["session_id"],
        job_id=result["job_id"],
        questions=[QuestionOut(**q) for q in result["questions"]],
    )


@router.get(
    "/jobs/{job_id}/latest-session",
    response_model=PrepSessionOut,
    summary="Get the most recent prep session for a job",
    responses=error_responses(ErrorCode.JOB_NOT_FOUND, ErrorCode.PREP_SESSION_NOT_FOUND),
)
async def get_latest_session(
    job_id: Annotated[int, Path(description="Job listing id")],
    session: Annotated[AsyncSession, Depends(get_session)],
) -> PrepSessionOut:
    """Return the newest session; PREP_SESSION_NOT_FOUND if the job has none yet."""
    job = await session.get(JobListing, job_id)
    if job is None:
        raise ApiError(ErrorCode.JOB_NOT_FOUND, "Job listing not found")

    result = await session.execute(
        select(InterviewSession)
        .where(InterviewSession.job_listing_id == job_id)
        .order_by(InterviewSession.id.desc())
        .limit(1)
    )
    interview = result.scalar_one_or_none()
    if interview is None:
        raise ApiError(ErrorCode.PREP_SESSION_NOT_FOUND, "No prep session found for this job")

    questions = json.loads(interview.questions)
    return PrepSessionOut(
        session_id=interview.id,
        job_id=job_id,
        questions=[QuestionOut(**q) for q in questions],
    )


@router.post(
    "/sessions/{session_id}/answer",
    response_model=AnswerFeedbackOut,
    summary="Submit an answer to a prep question",
    responses=error_responses(ErrorCode.SESSION_NOT_FOUND, ErrorCode.QUESTION_NOT_FOUND),
)
async def post_answer(
    session_id: SessionId,
    body: AnswerRequest,
    session: Annotated[AsyncSession, Depends(get_session)],
) -> AnswerFeedbackOut:
    """Stub: validates the session and question, then returns placeholder feedback.
    AI evaluation is out of scope since the coach skill migration."""
    try:
        result = await evaluate_answer(session, session_id, body.question_id, body.answer)
    except SessionNotFoundError as exc:
        raise ApiError(ErrorCode.SESSION_NOT_FOUND, str(exc)) from exc
    except QuestionNotFoundError as exc:
        raise ApiError(ErrorCode.QUESTION_NOT_FOUND, str(exc)) from exc

    return AnswerFeedbackOut(**result)


@router.get(
    "/sessions/{session_id}/summary",
    response_model=SessionSummaryOut,
    summary="Get a session's overall summary",
    responses=error_responses(ErrorCode.SESSION_NOT_FOUND),
)
async def get_summary(
    session_id: SessionId,
    session: Annotated[AsyncSession, Depends(get_session)],
) -> SessionSummaryOut:
    """Return the stored summary, or an empty placeholder if none was recorded."""
    try:
        result = await get_session_summary_data(session, session_id)
    except SessionNotFoundError as exc:
        raise ApiError(ErrorCode.SESSION_NOT_FOUND, str(exc)) from exc

    return SessionSummaryOut(
        session_id=result["session_id"],
        overall_score=result["overall_score"],
        summary=result["summary"],
        areas_to_improve=result["areas_to_improve"],
    )
