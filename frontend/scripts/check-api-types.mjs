// Generate (--write) or verify (default) src/lib/api-schema.d.ts from the backend's
// checked-in OpenAPI document. One code path for both so the check can never
// disagree with what gen:api writes.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const SPEC_URL = new URL("../../backend/openapi.yaml", import.meta.url);
const OUT_URL = new URL("../src/lib/api-schema.d.ts", import.meta.url);
const STALE = "api-schema.d.ts is out of date — run: cd frontend && npm run gen:api";
const HEADER = "// GENERATED by `npm run gen:api` from backend/openapi.yaml — do not edit.\n\n";

const ast = await openapiTS(SPEC_URL);
const rendered = HEADER + astToString(ast);

if (process.argv.includes("--write")) {
  writeFileSync(OUT_URL, rendered);
  console.log(`Wrote ${OUT_URL.pathname}`);
} else {
  const current = existsSync(OUT_URL) ? readFileSync(OUT_URL, "utf8") : null;
  if (current !== rendered) {
    console.error(STALE);
    process.exit(1);
  }
}
